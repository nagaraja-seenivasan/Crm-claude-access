-- =============================================================================
-- 000  Rule builder tables (backend models Rule, RuleExecutionLog)
-- MySQL 8.0+ (InnoDB, utf8mb4). All timestamps are UTC.
-- Column names match the `mysql.columnName` settings in backend/src/models.
-- =============================================================================

CREATE TABLE IF NOT EXISTS rule (
  id             CHAR(36)     NOT NULL COMMENT 'UUID, generated by the API',
  name           VARCHAR(255) NOT NULL,
  description    TEXT         NULL,
  entity_type    VARCHAR(64)  NOT NULL COMMENT 'Lead, Deal, Contact, Account, ...',
  is_active      TINYINT(1)   NOT NULL DEFAULT 0,
  trigger_types  JSON         NOT NULL COMMENT '["SQS","RECORD_SAVE"]',
  nodes          JSON         NOT NULL COMMENT 'RuleNodeSchema[]',
  connections    JSON         NOT NULL COMMENT 'NodeConnectionSchema[]',
  created_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY ix_rule_entity_active (entity_type, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- No foreign key to `rule`: execution history is kept when a rule is deleted.
CREATE TABLE IF NOT EXISTS rule_execution_log (
  id              CHAR(36)     NOT NULL COMMENT 'UUID, generated by the API',
  rule_id         CHAR(36)     NOT NULL,
  rule_name       VARCHAR(255) NOT NULL,
  entity_type     VARCHAR(64)  NOT NULL,
  entity_id       VARCHAR(64)  NULL,
  trigger_type    VARCHAR(32)  NOT NULL COMMENT 'SQS | RECORD_SAVE',
  outcome         VARCHAR(16)  NOT NULL COMMENT 'completed | failed | skipped',
  nodes_executed  JSON         NOT NULL,
  error_message   TEXT         NULL,
  scope_snapshot  JSON         NULL,
  executed_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY ix_rule_log_rule_time (rule_id, executed_at),
  KEY ix_rule_log_entity_time (entity_type, executed_at),
  KEY ix_rule_log_outcome_time (outcome, executed_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
